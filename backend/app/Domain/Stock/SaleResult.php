<?php

declare(strict_types=1);

namespace App\Domain\Stock;

/**
 * Итог продажи единицы, удержанной заказом на момент оплаты (см. 6.4 спеки).
 *
 * Объявлен в задаче 4a вместе с сигнатурой StockService::sellForOrder, а
 * заполняется он реализацией метода в задаче 6 — тип обязан существовать
 * уже сейчас, потому что от него зависит форма контракта StockService,
 * которым задача 4a пользуется (reserve, alternativeFor).
 */
enum SaleResult
{
    /** Единица, которую заказ уже держал в брони, продана без перезахвата. */
    case SoldHeld;

    /** Бронь была снята и отдана другому — продана другая единица того же предложения. */
    case SoldReclaimed;

    /** Свободных единиц предложения не осталось вовсе. */
    case NoStock;
}
