<?php

declare(strict_types=1);

namespace App\Domain\Realtime;

/**
 * Позиция одного SSE-подключения в журнале событий.
 *
 * Курсор существует из-за того, что `bigserial` выдаёт номер строки в момент
 * INSERT, а видимой строка становится в момент COMMIT. Между этими двумя
 * моментами лежит вся остальная работа транзакции (захват единицы, обновление
 * заказа, промокод), поэтому порядок появления строк в журнале НЕ обязан
 * совпадать с порядком их номеров: транзакция, взявшая номер 1001, может
 * закоммититься позже транзакции с номером 1002.
 *
 * Наивный догоняющий опрос `WHERE id > максимальный_отданный` в такой
 * ситуации пропускает опоздавшую строку НАВСЕГДА: 1002 отдан, значит
 * следующий запрос идёт от 1002, а 1001 остаётся за его границей. Именно
 * поэтому здесь два разных понятия вместо одного:
 *
 *  - `contiguous` — граница, до которой журнал обработан НЕПРЕРЫВНО. Только
 *    её и разрешено использовать как нижнюю границу чтения: пока 1001 не
 *    появился, чтение продолжает идти от 1000, и опоздавшая строка будет
 *    прочитана, как только станет видимой;
 *  - память о конкретных отданных номерах — чтобы повторное чтение от
 *    отставшей границы не отправило клиенту 1002 второй раз.
 *
 * Память об отданных id заведена кольцевым буфером на 1000 последних, а не
 * простым максимумом из 4.3 спеки: максимум отвечает на вопрос «докуда
 * дошли», а для подавления повторов нужен ответ на вопрос «этот конкретный
 * номер уже уходил», то есть проверка принадлежности множеству. Буфер
 * кольцевой, потому что процесс живёт неделями: неограниченное множество
 * отданных id превратилось бы в утечку памяти, линейную по числу событий.
 *
 * Курсор — на подключение, а не на процесс: у каждого клиента свой
 * `Last-Event-ID` (спека 4.4), и общая на всех граница чтения либо гоняла бы
 * всем чужой хвост, либо теряла бы события отставшего подключения.
 */
final class EventCursor
{
    /**
     * Сколько ждать заполнения дырки, прежде чем перескочить её.
     *
     * Ждать вечно нельзя: номер мог быть выделен транзакцией, которая
     * откатилась (отказ захвата единицы по 6.1 спеки — совершенно штатный
     * случай), и тогда строки с этим номером не будет никогда, а граница
     * непрерывности осталась бы стоять до перезапуска процесса.
     *
     * Три секунды — осознанный компромисс, а не круглое число: транзакции
     * витрины живут единицы-десятки миллисекунд, так что запас на два
     * порядка. Цена перескока: если транзакция всё же коммитится позже
     * трёх секунд, её событие для этого подключения потеряно. Потеря
     * самолечится — payload несёт полное состояние объекта (4.1 спеки),
     * поэтому следующее событие по тому же предложению приводит клиента в
     * актуальное состояние, а `resync` и снапшот закрывают худший случай.
     */
    private const GRACE = 3.0;

    /**
     * Размер кольцевого буфера отданных id (см. описание класса).
     *
     * Граница честная, а не бесконечная: если выше незаполненной дырки
     * успеет накопиться больше тысячи событий, самые ранние вытеснятся из
     * памяти и при следующем чтении уйдут клиенту повторно. Это допустимая
     * цена, а не дефект: payload несёт полное состояние объекта, поэтому
     * повторное применение ничего не меняет (4.1 спеки), а клиент вдобавок
     * страхуется гардом по версии на объект (4.6). Альтернатива —
     * неограниченная память процесса, который живёт неделями.
     */
    private const MEMORY = 1000;

    private int $contiguous;

    /**
     * Обработанные номера, лежащие ВЫШЕ границы непрерывности, то есть
     * ожидающие, когда цепочка до них дотянется. Набор мал по построению:
     * он опустошается по мере заполнения дырок и не растёт быстрее, чем
     * идут события в один незакрытый промежуток.
     *
     * @var array<int, true>
     */
    private array $pending = [];

    /**
     * Кольцевой буфер и карта принадлежности живут парой: кольцо помнит
     * ПОРЯДОК вытеснения, карта даёт проверку за O(1). Одной структурой это
     * не выражается — упорядоченный список требовал бы линейного поиска,
     * а карта сама не знает, кого вытеснять первым.
     *
     * @var array<int, int>
     */
    private array $ring = [];

    /** @var array<int, true> */
    private array $delivered = [];

    private int $writes = 0;

    /**
     * Момент, с которого ждём заполнения текущей дырки. null — дырки нет.
     */
    private ?float $holeSince = null;

    public function __construct(int $start)
    {
        // Отрицательный Last-Event-ID клиент присылать не должен, но граница
        // чтения — это то, что уходит в SQL, и она обязана быть валидной
        // независимо от того, что пришло по сети.
        $this->contiguous = max(0, $start);
    }

    /**
     * Помечает номер обработанным: событие поставлено в очередь отправки
     * клиенту (или сознательно отфильтровано как чужой топик).
     *
     * Ставится в очередь, а не «доставлено по сети»: подавление повторов
     * должно срабатывать до того, как байты уйдут в сокет, иначе повторное
     * чтение от отставшей границы успело бы отправить событие второй раз,
     * пока первое лежит в буфере записи.
     */
    public function observe(int $id): void
    {
        // Повторное наблюдение того же номера пришлось бы вытеснять из кольца
        // дважды, и вытеснение первой копии сняло бы отметку у второй — то
        // есть «уже отдано» превратилось бы в «не отдано» раньше срока.
        if (isset($this->delivered[$id])) {
            return;
        }

        $slot = $this->writes % self::MEMORY;

        if (isset($this->ring[$slot])) {
            unset($this->delivered[$this->ring[$slot]]);
        }

        $this->ring[$slot] = $id;
        $this->delivered[$id] = true;
        $this->writes++;

        if ($id > $this->contiguous) {
            $this->pending[$id] = true;
        }
    }

    public function wasDelivered(int $id): bool
    {
        return isset($this->delivered[$id]);
    }

    /**
     * Граница непрерывной обработки — нижняя граница следующего чтения
     * журнала (`WHERE id > contiguous`).
     */
    public function contiguous(): int
    {
        return $this->contiguous;
    }

    /**
     * Двигает границу непрерывности; при затянувшейся дырке — перескакивает.
     *
     * Время передаётся аргументом, а не берётся из `microtime`, по двум
     * причинам: цикл событий уже знает текущее время (одно измерение на
     * итерацию вместо одного на подключение) и тайм-аут дырки становится
     * проверяемым обычным юнит-тестом, без сна в три секунды.
     */
    public function advance(float $now): void
    {
        $moved = $this->walkChain();

        if ($this->pending === []) {
            // Ждать нечего: всё обработанное лежит ниже границы.
            $this->holeSince = null;

            return;
        }

        // Отсчёт ожидания — на КАЖДУЮ дырку свой. Если цепочка только что
        // сдвинулась, оставшийся промежуток — уже другая дырка, и ей нельзя
        // отдавать время, потраченное на предыдущую: иначе вторая дырка
        // перескакивалась бы раньше своих трёх секунд.
        if ($moved || $this->holeSince === null) {
            $this->holeSince = $now;

            return;
        }

        if ($now - $this->holeSince < self::GRACE) {
            return;
        }

        // Перескок к ближайшему обработанному номеру: ставим границу перед
        // ним и даём цепочке уехать дальше обычным ходом.
        $this->contiguous = min(array_keys($this->pending)) - 1;
        $this->walkChain();

        $this->holeSince = $this->pending === [] ? null : $now;
    }

    /**
     * Протягивает границу по непрерывной цепочке `+1`.
     *
     * @return bool двинулась ли граница
     */
    private function walkChain(): bool
    {
        $moved = false;

        while (isset($this->pending[$this->contiguous + 1])) {
            $this->contiguous++;
            unset($this->pending[$this->contiguous]);
            $moved = true;
        }

        return $moved;
    }
}
